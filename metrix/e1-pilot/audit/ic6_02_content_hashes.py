"""ic6_02 (implementation stage C, C1 second submission, fix commit, round 1; definition item 1): the four frozen content
hashes recomputed by me from the data directory regenerated by the formal code this round (<data_d>;
reports/impl_c/c1b_04_checks_fix.txt), byte sha256 of the 8 data files, and the check that the fix commit does not
touch the code that builds the data or the content hashes. My ic5_02 with the Executor's output of this round
(c1b_04_checks_fix.txt) as the comparison file; section D replaced (HEAD is now ae60e0f, whose tree 365960a0 is the one
my ic5_02 section D checked against the code before C1).
  A. PROTOCOL_FROZEN read by my own method (current-version section, frozen commit, table "全部数据哈希"; my labels of
     the four content rows; each row's location resolved in the frozen-commit manifest with git cat-file).
  B. the four hashes recomputed from <data_d> by the protocol rules (section 0 canonical JSON / JSONL; 2.2 facts: the
     six fields of every line in file order; 2.6 train_S JSONL; 2.5 candidates object; anchor texts: JSON list of
     the 512 texts in document order, also from my own decode of the anchor ids with the pinned Qwen tokenizer --
     tokenizer only, no model), compared with A and with the values the Executor printed this round.
  C. byte sha256 of the 8 files of <data_d> against my stage-B values (audit/stdout/impl_b/36_id_compare.txt, section
     D) and against the Executor's listing in c1b_04_checks_fix.txt; no TEST file in <data_d>.
  D. the staged change (git diff --cached HEAD --name-only) is exactly the 7 paths of the review input; none of the
     modules that generate or verify the data or compute the content hashes (data.py, frozen.py, leakage.py, gate.py,
     record.py, contract.py, interpretations.py, tokenize / template helpers: every src module except evaluate.py,
     test_data.py, testgate.py) changes; evaluate.py, test_data.py and testgate.py are not imported by data.py or
     frozen.py (import lines read as text); HEAD's tree is 365960a0, the tree of my round-1 audit.
Data Auditor's own script; no Executor code imported, called or copied.
usage: python -I ic6_02_content_hashes.py <repo_root> <qwen_tok_dir> <data_d>"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import datetime
import json
import re
from ia_common import FROZEN, git, blob, sha, canon, jsonl_bytes, read_jsonl, load_qwen, run

PF = "metrix/e1-pilot/PROTOCOL_FROZEN"
EX_OUT = "metrix/e1-pilot/reports/impl_c/c1b_04_checks_fix.txt"
FACT_FIELDS = ["fact_id", "exposure", "relation", "stratum", "entity", "answer"]
DATA = ["facts.jsonl", "train_F.jsonl", "train_S.jsonl", "train_Y.jsonl", "dev_qa.jsonl", "candidates.json",
        "general_dev.jsonl", "anchor_text.jsonl"]
MY_ROWS = {"facts": ("fact(160 条)", "协议第 2.2 节"), "train_S": ("`train_S.jsonl`", "协议第 2.6 节"),
           "candidates": ("`candidates.json`", "协议第 2.5 节"), "anchor_texts": ("锚文本(512 篇解码文本)", "JSON 列表")}
KEYS = ["facts", "train_S", "candidates", "anchor_texts"]


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def main():
    repo, qdir, dd = sys.argv[1:4]
    ok = True
    print("== A. PROTOCOL_FROZEN, my own reading")
    wt = open(os.path.join(repo, PF), "rb").read()
    print("%s sha256 %s | == HEAD blob %s | == index blob %s" % (PF, sha(wt), wt == blob(repo, "HEAD", PF),
                                                               wt == git(repo, "cat-file", "blob", ":" + PF).stdout))
    lines = wt.decode("utf-8").split("\n")
    ver = [ln.split("：", 1)[1].strip() for ln in lines if ln.startswith("当前有效版本：")]
    s0 = lines.index("## %s(当前有效)" % ver[0])
    s1 = next(i for i in range(s0 + 1, len(lines)) if lines[i].startswith("## "))
    crow = [cells(ln) for ln in lines[s0:s1] if ln.startswith("|") and cells(ln)[0] == "%s 冻结提交(完整 hash)" % ver[0]]
    commit = crow[0][1].strip("`")
    print("current version %s | frozen commit %s | == %s: %s" % (ver, commit, FROZEN, commit == FROZEN))
    ok &= ver == ["v1.1"] and commit == FROZEN
    th = lines.index("### 全部数据哈希")
    table, prev = {}, None
    for ln in lines[th + 1:]:
        if ln.startswith("#"):
            break
        if ln.startswith("|"):
            c = cells(ln)
            if re.fullmatch(r"`[0-9a-f]{64}`", c[1]):
                where = prev if c[3] == "同上" else c[3].strip("`")
                prev = where
                table[c[0]] = (c[1].strip("`"), c[2], where)
    print("table rows with a 64-hex value: %d" % len(table))
    ok &= len(table) == 12
    frozen_vals = {}
    for k in KEYS:
        label, dmark = MY_ROWS[k]
        v, dfn, where = table[label]
        fname, path = where.split(": ", 1)
        x = json.loads(blob(repo, FROZEN, "metrix/e1-pilot/" + fname))
        for part in path.split("."):
            x = x[part]
        print("  %-12s row %r -> %s | definition names %r: %s | frozen-commit %s: %s == value: %s" % (
            k, label, v, dmark, dmark in dfn, fname, path, x == v))
        ok &= dmark in dfn and x == v
        frozen_vals[k] = v

    print("\n== B. recomputed from %s by the protocol rules" % dd)
    for n in DATA:
        st = os.stat(os.path.join(dd, n))
        print("  %-18s size %7d mtime %s UTC" % (n, st.st_size, datetime.datetime.utcfromtimestamp(st.st_mtime).strftime("%Y-%m-%d %H:%M:%S")))
    raw = read_jsonl(os.path.join(dd, "facts.jsonl"))
    six = all(sorted(r) == sorted(FACT_FIELDS) for r in raw)
    facts = [{f: r[f] for f in FACT_FIELDS} for r in raw]
    s_rows = read_jsonl(os.path.join(dd, "train_S.jsonl"))
    cands = json.load(open(os.path.join(dd, "candidates.json"), encoding="utf-8"))
    anchor = read_jsonl(os.path.join(dd, "anchor_text.jsonl"))
    order = [r["doc"] for r in anchor] == list(range(len(anchor)))
    print("facts.jsonl %d lines (each exactly the 6 fields: %s) | train_S.jsonl %d rows | candidates.json %d facts | "
          "anchor_text.jsonl %d rows (doc == line index: %s)" % (len(raw), six, len(s_rows), len(cands), len(anchor), order))
    ok &= six and order and len(raw) == 160 and len(s_rows) == 120 and len(cands) == 160 and len(anchor) == 512
    tok = load_qwen(qdir)
    dec = [tok.decode(r["ids"]) for r in anchor]
    mine = {"facts": sha(canon(facts)), "train_S": sha(jsonl_bytes(s_rows)), "candidates": sha(canon(cands)),
            "anchor_texts": sha(canon([r["text"] for r in anchor]))}
    print("anchor texts from my decode of the stored ids (pinned Qwen tokenizer): %s | every decoded text == stored text: %s" % (
        sha(canon(dec)), dec == [r["text"] for r in anchor]))
    ok &= sha(canon(dec)) == mine["anchor_texts"] and dec == [r["text"] for r in anchor]
    ex = open(os.path.join(repo, EX_OUT), encoding="utf-8").read()
    gen = dict(re.findall(r"^frozen content hash (\w+)\s+([0-9a-f]{64}) = PROTOCOL_FROZEN \(read back from [^)]*c1_data\)$", ex, re.M))
    ver_ = dict(re.findall(r"^frozen content hash (\w+)\s+([0-9a-f]{64}) = PROTOCOL_FROZEN$", ex, re.M))
    print("Executor's values from %s: generation %d lines, verify %d lines" % (EX_OUT, len(gen), len(ver_)))
    for k in KEYS:
        same = mine[k] == frozen_vals[k] == gen.get(k) == ver_.get(k)
        print("  %-12s mine %s | PROTOCOL_FROZEN %s | Executor generate %s | Executor verify %s | ALL EQUAL %s" % (
            k, mine[k], frozen_vals[k], gen.get(k), ver_.get(k), same))
        ok &= same

    print("\n== C. byte sha256 of the data files")
    r3 = open(os.path.join(repo, "metrix/e1-pilot/audit/stdout/impl_b/36_id_compare.txt"), encoding="utf-8").read()  # my stage-B record
    rec3 = dict(re.findall(r"^  (\S+): rows \d+ \| byte ([0-9a-f]{64}) \|", r3, re.M))
    exl = dict(re.findall(r"^(\S+)\s+rows\s+\d+\s+byte_sha256 ([0-9a-f]{64})", ex, re.M))
    for n in DATA:
        now = sha(open(os.path.join(dd, n), "rb").read())
        same = now == rec3.get(n) == exl.get(n)
        print("  %-18s now %s | my stage-B record %s | Executor listing (c1b_04) %s | equal %s" % (n, now, rec3.get(n), exl.get(n), same))
        ok &= same
    present = sorted(os.listdir(dd))
    print("  files in data_d: %s | test_qa.jsonl / general_test.jsonl present: %s" % (
        present, [x for x in ("test_qa.jsonl", "general_test.jsonl") if x in present]))
    ok &= present == sorted(DATA)

    print("\n== D. the fix commit and the data code")
    head_tree = git(repo, "rev-parse", "HEAD^{tree}").stdout.decode().strip()
    print("HEAD %s tree %s (my round-1 audit tree 365960a0e2c5cc28869be9ed44a08d4170389633): %s" % (
        git(repo, "rev-parse", "HEAD").stdout.decode().strip(), head_tree, head_tree == "365960a0e2c5cc28869be9ed44a08d4170389633"))
    ok &= head_tree == "365960a0e2c5cc28869be9ed44a08d4170389633"
    changed = git(repo, "diff", "--cached", "--name-only", "HEAD").stdout.decode().split()
    want = ["metrix/e1-pilot/reports/impl_c/c1b_03_checks_fix.txt", "metrix/e1-pilot/reports/impl_c/c1b_04_checks_fix.txt",
            "metrix/e1-pilot/reports/impl_c/c1b_mutate_fix1.py", "metrix/e1-pilot/src/metrix_e1/evaluate.py",
            "metrix/e1-pilot/src/metrix_e1/test_data.py", "metrix/e1-pilot/src/metrix_e1/testgate.py",
            "metrix/e1-pilot/tests/test_testgate.py"]
    print("staged paths vs HEAD: %s | == the 7 paths of the review input: %s" % (changed, sorted(changed) == sorted(want)))
    ok &= sorted(changed) == sorted(want)
    pkg = "metrix/e1-pilot/src/metrix_e1/"
    mods = sorted(p.split("/")[-1] for p in git(repo, "ls-files", pkg).stdout.decode().split() if p.endswith(".py"))
    same = {m: git(repo, "cat-file", "blob", "HEAD:" + pkg + m).stdout == git(repo, "cat-file", "blob", ":" + pkg + m).stdout
            == open(os.path.join(repo, pkg + m), "rb").read() for m in mods}
    print("package modules unchanged (HEAD blob == index blob == working tree): %s" % sorted(m for m, s in same.items() if s))
    print("package modules changed: %s" % sorted(m for m, s in same.items() if not s))
    ok &= sorted(m for m, s in same.items() if not s) == ["evaluate.py", "test_data.py", "testgate.py"]
    for m in ("data.py", "frozen.py"):
        imps = [ln.strip() for ln in open(os.path.join(repo, pkg + m), encoding="utf-8").read().split("\n")
                if re.match(r"\s*(from|import)\s", ln)]
        bad = [ln for ln in imps if re.search(r"\b(evaluate|test_data|testgate)\b", ln)]
        print("  %s import lines: %s | import evaluate / test_data / testgate: %s" % (m, imps, bad))
        ok &= bad == []
    print("conclusion: the data and content-hash code is the code of my round-1 audit (ic5_02, ALL EQUAL); the data files "
          "below are byte-identical to the stage-B data, so my earlier L1-L6, feasibility and split results apply")
    return bool(ok)


run(main)
