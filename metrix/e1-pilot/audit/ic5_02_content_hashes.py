    rec3 = dict(re.findall(r"^  (\S+): rows \d+ \| byte ([0-9a-f]{64}) \|", r3, re.M))
    exl = dict(re.findall(r"^(\S+)\s+rows\s+\d+\s+byte_sha256 ([0-9a-f]{64})", ex, re.M))
    for n in DATA:
        now = sha(open(os.path.join(dd, n), "rb").read())
        same = now == rec3.get(n) == exl.get(n)
        print("  %-18s now %s | my stage-B record %s | Executor listing (c1b_02) %s | equal %s" % (n, now, rec3.get(n), exl.get(n), same))
        ok &= same
    present = sorted(os.listdir(dd))
    print("  files in data_d: %s | test_qa.jsonl / general_test.jsonl present: %s" % (
        present, [x for x in ("test_qa.jsonl", "general_test.jsonl") if x in present]))
