"""R8b-P: supplement b (protocol 2.5 of the freeze commit: a distractor pool with fewer than 4 answers ->
IMPLEMENTATION_FAIL, no synthetic distractors). Data Auditor's own script; no Executor code is imported, called or
copied. Exceptions -> RESULT: FAIL (r6_guard). Loads the tokenizer only (four-file directory), never weights.

Input: the 160 facts regenerated by the auditor (r8_facts.py, DATA_SEED) - their canonical hash is checked against
the freeze-commit manifest first.
  a. the rule text in the freeze commit: protocol 2.5 sentence, SPLIT_MANIFEST candidates.pool_too_small, the pool
     definition and the stated pool sizes ("learned 14 个,unread 4 个" / "14 for learned, 4 for unread");
  b. per fact: pool = answers of the OTHER facts with the same relation, stratum and exposure (protocol 2.5);
     pool size (count), distinct answers in the pool, own answer not in pool; per-exposure sizes, minimum, number of
     facts with pool < 4 (-> IMPLEMENTATION_FAIL if > 0);
  c. per cell (relation, stratum, exposure) the number of facts and the minimum pool;
  d. auditor definition item 3 (four constraints: same relation, stratum, exposure AND same answer token count):
     the same pool restricted to answers whose Qwen token counts equal the fact's own answer, for the counts
     len(encode(" " + a)), len(encode(a)) and the pair; minimum and facts / cells with < 4 (shown against the same
     threshold; the frozen protocol defines the pool by the first three constraints only);
  e. the candidates.json rebuilt by r8_s_cands.py: every distractor of every fact lies in the fact's pool.
Prints AUDIT_VALUE-style lines "POOL_VALUE <key> <value>" for r8b_compare.py.
PASS iff the facts hash matches, the rule text is present, the stated sizes equal the computed ones, and no fact has
a pool with fewer than 4 answers (i.e. the rule does not fire under DATA_SEED).
usage: python -I r8b_pool.py <repo_root> <commit> <facts.json> <candidates.json> <qwen_tok_dir>"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import json, subprocess
from collections import Counter, defaultdict
from common import sha, canon, load_tok, enc
from r6_guard import run


def git_blob(repo, commit, path):
    return subprocess.run(["git", "-C", repo, "cat-file", "blob", f"{commit}:{path}"], capture_output=True, check=True).stdout


def main():
    repo, commit, facts_path, cands_path, tokdir = sys.argv[1:6]
    ok = True
    dm = json.loads(git_blob(repo, commit, "metrix/e1-pilot/DATA_MANIFEST.json"))
    sm = json.loads(git_blob(repo, commit, "metrix/e1-pilot/SPLIT_MANIFEST.json"))
    proto = git_blob(repo, commit, "metrix/e1-pilot/METRIX_E1_PROTOCOL.md").decode("utf-8")

    print("== a. rule text in the freeze commit")
    s1 = "- 干扰项的池少于 4 个答案即 IMPLEMENTATION_FAIL,不生成合成干扰项。"
    s0 = "- **干扰项的池**:同 relation、同 stratum、同暴露类别(learned 或 unread)的其它 fact 的答案。"
    s2 = "不含该 fact 自己(learned 14 个,unread 4 个)"
    lines = proto.splitlines()
    for s in (s0, s1, s2):
        hit = [i + 1 for i, l in enumerate(lines) if s in l]
        print(f"  protocol contains {s!r}: lines {hit}")
        ok &= bool(hit)
    i0 = next(i for i, l in enumerate(lines) if s0 in l)
    i1 = next(i for i, l in enumerate(lines) if s1 in l)
    sec = [l for l in lines[:i1] if l.startswith("### ")][-1]
    print("  new sentence directly follows the pool definition:", i1 == i0 + 1, "| section:", sec)
    impl = [l for l in lines if l.startswith("| IMPLEMENTATION_FAIL |")]
    print("  section 9 IMPLEMENTATION_FAIL row mentions the 2.5 pool rule:",
          bool(impl) and "第 2.5 节干扰项的池少于 4 个答案" in impl[0])
    ok &= bool(impl) and "第 2.5 节干扰项的池少于 4 个答案" in impl[0]
    c = sm["candidates"]
    print("  SPLIT_MANIFEST candidates.pool:", c.get("pool"))
    print("  SPLIT_MANIFEST candidates.pool_too_small:", c.get("pool_too_small"))
    print("  SPLIT_MANIFEST candidates.call_order mentions '(14 for learned, 4 for unread)':",
          "(14 for learned, 4 for unread)" in c.get("call_order", ""))
    ok &= isinstance(c.get("pool_too_small"), str) and "IMPLEMENTATION_FAIL" in c["pool_too_small"]
    ok &= "(14 for learned, 4 for unread)" in c.get("call_order", "")

    facts = json.load(open(facts_path, encoding="utf-8"))
    fh = sha(canon(facts))
    exp = dm["name_generation"]["expected_facts_canonical_sha256"]
    print(f"\nfacts: {len(facts)} | canonical sha256 {fh} | manifest {exp} | MATCH {fh == exp}")
    ok &= fh == exp and len(facts) == 160

    print("\n== b. pool per fact (same relation, stratum, exposure; other facts)")
    pools = {}
    for f in facts:
        pools[f["fact_id"]] = [g["answer"] for g in facts if g is not f and g["relation"] == f["relation"]
                               and g["stratum"] == f["stratum"] and g["exposure"] == f["exposure"]]
    sizes = {fid: len(p) for fid, p in pools.items()}
    distinct = {fid: len(set(p)) for fid, p in pools.items()}
    own_out = all(f["answer"] not in pools[f["fact_id"]] for f in facts)
    by_exp = {e: sorted(set(sizes[f["fact_id"]] for f in facts if f["exposure"] == e)) for e in ("learned", "unread")}
    by_exp_d = {e: sorted(set(distinct[f["fact_id"]] for f in facts if f["exposure"] == e)) for e in ("learned", "unread")}
    mn = min(sizes.values())
    mn_d = min(distinct.values())
    small = sorted(fid for fid, n in sizes.items() if n < 4)
    small_d = sorted(fid for fid, n in distinct.items() if n < 4)
    print("  pool size (count) by exposure:", by_exp, "| distinct answers by exposure:", by_exp_d)
    print("  own answer never in own pool:", own_out)
    print("  minimum pool size:", mn, "| minimum distinct:", mn_d)
    print("  facts with pool < 4:", len(small), small, "| with distinct < 4:", len(small_d), small_d)
    print("  size histogram:", dict(sorted(Counter(sizes.values()).items())))
    print("  IMPLEMENTATION_FAIL by the 2.5 rule under DATA_SEED:", bool(small or small_d))
    print(f"POOL_VALUE sizes_learned {by_exp['learned']}")
    print(f"POOL_VALUE sizes_unread {by_exp['unread']}")
    print(f"POOL_VALUE minimum {mn}")
    print(f"POOL_VALUE facts_below_4 {len(small)}")
    ok &= own_out and not small and not small_d
    ok &= by_exp == {"learned": [14], "unread": [4]}

    print("\n== c. per cell (relation, stratum, exposure)")
    cells = defaultdict(list)
    for f in facts:
        cells[(f["relation"], f["stratum"], f["exposure"])].append(f["fact_id"])
    for k in sorted(cells):
        ids = cells[k]
        print(f"  {k[0]:<8} {k[1]:<7} {k[2]:<7} facts {len(ids):>2} | min pool {min(sizes[i] for i in ids)}")
    print("  cells:", len(cells))
    ok &= len(cells) == 16

    print("\n== d. four constraints (+ same answer token count, Qwen tokenizer)")
    tok = load_tok(tokdir)
    print("  tokenizer dir files:", sorted(x for x in os.listdir(tokdir) if not x.startswith(".")), "| class", type(tok).__name__)
    kn = {f["fact_id"]: (len(enc(tok, " " + f["answer"])), len(enc(tok, f["answer"]))) for f in facts}
    by_id = {f["fact_id"]: f for f in facts}
    for label, key in (("len(encode(' ' + answer))", lambda p: p[0]), ("len(encode(answer))", lambda p: p[1]),
                       ("pair", lambda p: p)):
        n4 = {}
        for f in facts:
            n4[f["fact_id"]] = sum(1 for g in facts if g is not f and g["relation"] == f["relation"]
                                   and g["stratum"] == f["stratum"] and g["exposure"] == f["exposure"]
                                   and key(kn[g["fact_id"]]) == key(kn[f["fact_id"]]))
        low = sorted(fid for fid, n in n4.items() if n < 4)
        cell_low = sorted({"/".join((by_id[fid]["relation"], by_id[fid]["stratum"], by_id[fid]["exposure"])) for fid in low})
        print(f"  {label}: minimum {min(n4.values())} | facts < 4: {len(low)} | cells with a fact < 4: {cell_low} | "
              f"equal to the 3-constraint pool for every fact: {all(n4[i] == sizes[i] for i in n4)}")
    per_cell_pairs = {k: sorted({kn[i] for i in ids}) for k, ids in cells.items()}
    print("  answer token-count pairs per cell (' '+a, a):")
    for k in sorted(per_cell_pairs):
        print(f"    {'/'.join(k)}: {per_cell_pairs[k]}")
    ok &= all(len(v) == 1 for v in per_cell_pairs.values())

    print("\n== e. rebuilt candidates.json distractors lie in the pool")
    cands = json.load(open(cands_path, encoding="utf-8"))
    ch = sha(canon(cands))
    print("  candidates canonical sha256", ch, "| == SPLIT_MANIFEST candidate_mapping_sha256:", ch == c["candidate_mapping_sha256"])
    ok &= ch == c["candidate_mapping_sha256"]
    inpool = all(set(v) - {by_id[k]["answer"]} <= set(pools[k]) and len(set(v)) == 4 and v.count(by_id[k]["answer"]) == 1
                 for k, v in cands.items())
    print("  every fact: 4 distinct candidates, true answer once, 3 distractors from its pool:", inpool, "| keys", len(cands))
    ok &= inpool and len(cands) == 160
    return ok


run(main)
