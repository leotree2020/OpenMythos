#!/usr/bin/env python3
"""R1 Gate B: read-only evaluation of the actual trained tiny language-model checkpoint.

Compare model byte-token NLL with uniformly random, train-fitted smoothed
unigram and train-fitted smoothed bigram baselines on IDENTICAL heldout windows.
Check whether greedy output collapses to frequent whitespace/characters.
Only uses existing local text/checkpoint; no network or optimizer update.
"""
import argparse
from dataclasses import asdict
import json
import math
from pathlib import Path

import torch
import torch.nn.functional as F

from common import atomic_json, commit_id, get_repo, load_upstream
from r1_text_pilot import (VOCAB_SIZE, EOS, TOKENIZER_ID, text_tokens,
                           validation_offsets)


def fitted_byte_models(training, smoothing=1.0):
    """Maximum-likelihood byte-token unigrams/bigrams with additive smoothing."""
    if not torch.is_tensor(training) or training.ndim != 1 or training.numel() < 2:
        raise ValueError("Training token vector must be 1-D with >=2 elements")
    if not 0 < smoothing <= 100:
        raise ValueError("Smoothing must be in (0,100]")
    if int(training.min()) < 0 or int(training.max()) >= VOCAB_SIZE:
        raise ValueError("Invalid byte-token ids")
    targets = training[1:].long()
    counts = torch.bincount(targets, minlength=VOCAB_SIZE).double()
    unigrams = (counts + smoothing) / (counts.sum() + smoothing * VOCAB_SIZE)

    transitions = training[:-1].long() * VOCAB_SIZE + targets
    joint = torch.bincount(
        transitions, minlength=VOCAB_SIZE * VOCAB_SIZE
    ).reshape(VOCAB_SIZE, VOCAB_SIZE).double()
    bigrams = (joint + smoothing) / (
        joint.sum(dim=1, keepdim=True) + smoothing * VOCAB_SIZE
    )
    return unigrams, bigrams


def byte_metrics(ids):
    """Content-collapse metrics for sampled next-token bytes (not a fluency score)."""
    if not all(0 <= int(i) < 256 for i in ids):
        raise ValueError("Generated bytes must be in [0,255]")
    if not ids:
        return {"tokens": 0, "space_fraction": 0., "whitespace_fraction": 0.,
                "unique_bytes": 0, "longest_single_byte_run": 0}
    longest = current = 1
    for before, after in zip(ids, ids[1:]):
        current = current + 1 if before == after else 1
        longest = max(longest, current)
    return {"tokens": len(ids), "space_fraction": ids.count(32) / len(ids),
            "whitespace_fraction": sum(i in (9, 10, 13, 32) for i in ids) / len(ids),
            "unique_bytes": len(set(ids)), "longest_single_byte_run": longest}


def metrics_from_sums(nll_sum, count):
    if count == 0:
        return {"nll": None, "ppl": None, "tokens": 0}
    nll = nll_sum / count
    if not math.isfinite(nll):
        raise RuntimeError("Nonfinite heldout baseline or model NLL")
    return {"nll": nll, "ppl": math.exp(min(nll, 60.)), "tokens": count}


@torch.no_grad()
def compare_heldout(model, training, validation, *, seq_len, n_loops,
                    n_windows, device):
    """Equal validation targets for all baselines; no train-set evaluation leakage."""
    model.eval()
    unigram, bigram = fitted_byte_models(training)
    aggregations = {name: {"nll_sum": 0., "tokens": 0} for name in (
        "model", "unigram", "bigram", "uniform", "model_space",
        "model_nonspace", "model_nonwhitespace"
    )}
    position_count = predicted_spaces = true_spaces = correct = 0
    greedy_hist = torch.zeros(VOCAB_SIZE, dtype=torch.long)
    for offset in validation_offsets(len(validation), seq_len, n_windows):
        x = validation[offset:offset + seq_len].long()
        y = validation[offset + 1:offset + seq_len + 1].long()
        logits = model(x.unsqueeze(0).to(device), n_loops=n_loops)
        per = F.cross_entropy(
            logits.reshape(-1, VOCAB_SIZE), y.to(device), reduction="none"
        ).detach().cpu().double()
        pred = logits[0].argmax(dim=-1).detach().cpu().long()
        true_spaces += int((y == 32).sum())
        predicted_spaces += int((pred == 32).sum())
        correct += int((pred == y).sum())
        position_count += len(y)
        greedy_hist += torch.bincount(pred, minlength=VOCAB_SIZE)

        masks = {
            "model": torch.ones(len(y), dtype=torch.bool),
            "model_space": y == 32,
            "model_nonspace": y != 32,
            "model_nonwhitespace": ((y != 32) & (y != 9) &
                                    (y != 10) & (y != 13)),
        }
        for label, mask in masks.items():
            aggregations[label]["nll_sum"] += float(per[mask].sum())
            aggregations[label]["tokens"] += int(mask.sum())

        for label, values in (
            ("unigram", -unigram[y].log()),
            ("bigram", -bigram[x, y].log()),
            ("uniform", torch.full((len(y),), math.log(VOCAB_SIZE),
                                   dtype=torch.double)),
        ):
            aggregations[label]["nll_sum"] += float(values.sum())
            aggregations[label]["tokens"] += len(y)

    result = {
        name: metrics_from_sums(item["nll_sum"], item["tokens"])
        for name, item in aggregations.items()
    }
    result["token_statistics"] = {
        "target_space_fraction": true_spaces / position_count,
        "predicted_space_fraction": predicted_spaces / position_count,
        "greedy_top1_accuracy": correct / position_count,
        "top1_distinct_byte_ids": int((greedy_hist > 0).sum()),
        "top1_most_common": [
            {"byte_id": int(i), "count": int(greedy_hist[i])}
            for i in torch.argsort(greedy_hist, descending=True)[:6]
            if int(greedy_hist[i]) > 0
        ],
    }
    result["windows"] = min(n_windows, len(validation_offsets(
        len(validation), seq_len, n_windows
    )))
    return result


@torch.no_grad()
def generate_diagnostic(model, prompt, *, n_loops, max_new_tokens, seq_len,
                        mode="greedy", top_k=32, temperature=0.9, seed=91,
                        device="cpu"):
    if mode not in ("greedy", "sample") or temperature <= 0 or top_k < 1:
        raise ValueError("Invalid generation settings")
    model.eval()
    prefix = list(prompt.encode("utf-8"))
    if not prefix:
        raise ValueError("Prompt cannot be empty")
    if max_new_tokens < 0:
        raise ValueError("max_new_tokens must be nonnegative")
    generated = []
    rng = torch.Generator(device="cpu").manual_seed(seed)
    stopped_eos = False
    for _ in range(max_new_tokens):
        x = torch.tensor([prefix[-seq_len:]], dtype=torch.long, device=device)
        logits = model(x, n_loops=n_loops)[0, -1].float().cpu()
        if mode == "greedy":
            next_id = int(logits.argmax())
        else:
            k = min(top_k, logits.numel())
            vals, idxs = logits.topk(k)
            probs = torch.softmax(vals / temperature, dim=-1)
            draw = torch.multinomial(probs, 1, generator=rng)
            next_id = int(idxs[draw])
        if next_id == EOS:
            stopped_eos = True
            break
        prefix.append(next_id)
        generated.append(next_id)
    return {
        "prompt": prompt, "mode": mode, "seed": seed if mode == "sample" else None,
        "generated_text": bytes(generated).decode("utf-8", errors="replace"),
        "generated_byte_ids": generated, "stopped_at_eos": stopped_eos,
        "metrics": byte_metrics(generated)
    }



@torch.no_grad()
def context_order_probe(model, validation, *, seq_len, n_loops, n_windows, device):
    """Controlled same-length context-order ablation at the last token of each window.

    Reverse *only* the previous seq_len-1 bytes; preserve the current last
    input byte and target, both lengths, and the exact multiset of history
    bytes. A nonzero change measures history-order sensitivity, not semantic
    understanding. Positive ΔNLL means original history predicts better.
    """
    if n_windows < 1:
        raise ValueError("n_windows must be positive")
    model.eval()
    actual_nll = reversed_nll = abs_max_total = tv_total = 0.0
    switches = 0
    offsets = validation_offsets(len(validation), seq_len, n_windows)
    for start in offsets:
        x = validation[start:start + seq_len].long()
        target = int(validation[start + seq_len])
        reversed_x = x.clone()
        reversed_x[:-1] = x[:-1].flip(0)

        logits_actual = model(
            x.unsqueeze(0).to(device), n_loops=n_loops
        )[0, -1].float().cpu()
        logits_reversed = model(
            reversed_x.unsqueeze(0).to(device), n_loops=n_loops
        )[0, -1].float().cpu()
        a_lp = torch.log_softmax(logits_actual, dim=-1)
        r_lp = torch.log_softmax(logits_reversed, dim=-1)
        actual_nll -= float(a_lp[target])
        reversed_nll -= float(r_lp[target])
        abs_max_total += float((logits_actual - logits_reversed).abs().max())
        tv_total += float(
            (a_lp.exp() - r_lp.exp()).abs().sum() * 0.5
        )
        switches += int(int(logits_actual.argmax()) != int(logits_reversed.argmax()))

    count = len(offsets)
    result = {
        "windows": count,
        "original_context_last_token_nll": actual_nll / count,
        "reversed_history_last_token_nll": reversed_nll / count,
        "reversed_minus_original_target_nll": (reversed_nll - actual_nll) / count,
        "mean_logits_max_abs_change": abs_max_total / count,
        "mean_probability_total_variation": tv_total / count,
        "argmax_changed_fraction": switches / count,
        "control": "Same window length, same final input byte and target; "
                   "earlier input bytes reversed (same histogram, changed order).",
        "interpretation": "Nonzero sensitivity does not prove beneficial context "
                          "understanding. Positive NLL delta favors original context "
                          "on selected last-token targets only.",
    }
    return result


def validate_checkpoint(checkpoint, report, config, train_meta, valid_meta):
    if checkpoint.get("format_version") != 1:
        raise ValueError("Unsupported checkpoint format")
    if checkpoint.get("cfg") != asdict(config):
        raise ValueError("Checkpoint configuration mismatch")
    if checkpoint.get("step") != report.get("target_step"):
        raise ValueError("Checkpoint step and training report disagree")
    if checkpoint.get("hyperparameters") != report.get("hyperparameters"):
        raise ValueError("Checkpoint hyperparameters and report disagree")
    fingerprints = {"tokenizer": TOKENIZER_ID, "train": train_meta,
                    "validation": valid_meta}
    if checkpoint.get("provenance") != fingerprints:
        raise ValueError("Checkpoint dataset provenance mismatch")
    if report.get("source_provenance") != fingerprints:
        raise ValueError("Report dataset provenance mismatch")


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--repo", default=".")
    p.add_argument("--pilot-dir", default="research/mini_mythos/results/r1/pilot_gqa")
    p.add_argument("--out", default=None)
    p.add_argument("--device", choices=("cpu", "cuda"), default="cpu")
    p.add_argument("--eval-windows", type=int, default=16)
    p.add_argument("--generated-bytes", type=int, default=64)
    a = p.parse_args()
    if a.eval_windows < 1 or not 0 <= a.generated_bytes <= 512:
        p.error("Invalid evaluation limits")
    if a.device == "cuda" and not torch.cuda.is_available():
        p.error("CUDA requested but is unavailable")
    root = get_repo(a.repo)
    directory = Path(a.pilot_dir).resolve()
    if not directory.is_relative_to(root / "research/mini_mythos/results"):
        p.error("Pilot dir must be under research/mini_mythos/results")
    output = Path(a.out).resolve() if a.out else directory / "diagnostics.json"
    if not output.is_relative_to(root / "research/mini_mythos/results"):
        p.error("Output must be under research/mini_mythos/results")
    report = json.loads((directory / "report.json").read_text(encoding="utf-8"))
    ckpt = torch.load(directory / "latest.pt", map_location="cpu",
                      weights_only=True)
    if report.get("tokenizer") != TOKENIZER_ID:
        raise ValueError("Tokenizer identifier mismatch")
    seq_len = report["hyperparameters"]["seq_len"]
    depth = report["hyperparameters"]["depth"]
    train_meta = report["source_provenance"]["train"]
    valid_meta = report["source_provenance"]["validation"]
    train, checked_train = text_tokens(
        train_meta["source_path"], train_meta["selected_bytes"], seq_len)
    validation, checked_val = text_tokens(
        valid_meta["source_path"], valid_meta["selected_bytes"], seq_len)

    torch.set_num_threads(min(4, torch.get_num_threads()))
    module = load_upstream(root)
    cfg = module.MythosConfig(**report["configuration"])
    validate_checkpoint(ckpt, report, cfg, checked_train, checked_val)
    model = module.OpenMythos(cfg).to(a.device).eval()
    model.load_state_dict(ckpt["model"], strict=True)
    stats = compare_heldout(model, train, validation, seq_len=seq_len,
                            n_loops=depth, n_windows=a.eval_windows,
                            device=a.device)
    if a.eval_windows == report["heldout_after_this_run"]["windows"]:
        prior = report["heldout_after_this_run"]["nll"]
        if abs(stats["model"]["nll"] - prior) > 5e-5:
            raise RuntimeError(
                f"Checkpoint heldout NLL {stats['model']['nll']:.6f} "
                f"does not reproduce recorded report NLL {prior:.6f}"
            )
    order_sensitivity = context_order_probe(
        model, validation, seq_len=seq_len, n_loops=depth,
        n_windows=a.eval_windows, device=a.device
    )
    examples = []
    for prompt in ("The ", "Once upon a time, ", "In the beginning, "):
        examples.append(generate_diagnostic(
            model, prompt, n_loops=depth, max_new_tokens=a.generated_bytes,
            seq_len=seq_len, mode="greedy", device=a.device))
        examples.append(generate_diagnostic(
            model, prompt, n_loops=depth, max_new_tokens=a.generated_bytes,
            seq_len=seq_len, mode="sample", temperature=0.9,
            top_k=32, seed=91, device=a.device))
    payload = {
        "experiment": "R1 Gate B read-only real-text checkpoint diagnostics",
        "repository_commit": commit_id(root), "checkpoint_step": ckpt["step"],
        "checkpoint_source": str(directory / "latest.pt"),
        "torch_version": torch.__version__, "tokenizer": TOKENIZER_ID,
        "train_bytes": len(train), "validation_bytes": len(validation),
        "model_heldout_and_baselines": stats,
        "context_order_probe": order_sensitivity,
        "generated_examples": examples,
        "limitations": "Byte-level PPL not comparable with other tokenizers. "
                       "Small validation sample and 60-step tiny training only. "
                       "Unigram/bigram fit on selected train prefix; no heldout leakage. "
                       "A low PPL or sampled legible bytes do not prove reasoning "
                       "or equivalence to Claude Mythos.",
    }
    atomic_json(output, payload)
    print("Model NLL / PPL:", stats["model"]["nll"], stats["model"]["ppl"])
    print("Unigram NLL / PPL:", stats["unigram"]["nll"], stats["unigram"]["ppl"])
    print("Bigram NLL / PPL:", stats["bigram"]["nll"], stats["bigram"]["ppl"])
    print("Uniform NLL / PPL:", stats["uniform"]["nll"], stats["uniform"]["ppl"])
    print("Model nonspace NLL:", stats["model_nonspace"]["nll"])
    print("Target space fraction:", stats["token_statistics"]["target_space_fraction"])
    print("Model predicts space fraction:", stats["token_statistics"]["predicted_space_fraction"])
    print("Reversed-context last-token delta NLL:",
          order_sensitivity["reversed_minus_original_target_nll"])
    print("Reversed-context mean probability TV:",
          order_sensitivity["mean_probability_total_variation"])
    for item in examples:
        print(item["mode"], repr(item["prompt"]),
              repr(item["generated_text"]),
              "space_fraction=", round(item["metrics"]["space_fraction"], 3))
    print("Saved:", output)


if __name__ == "__main__":
    main()
