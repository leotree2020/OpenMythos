#!/usr/bin/env python3
"""Turn a `pip install --dry-run --report` JSON into a hash-pinned requirements.lock and review it.

A pip resolution report is not a lock file. This tool:
  * pins every package of the resolved closure to its exact version and artifact SHA-256,
  * rejects source distributions (binary wheels only),
  * checks that each PyPI release is at least --min-age-days older than --lock-date,
  * records non-PyPI artifacts (e.g. the PyTorch CPU wheel) with their host, without an age check.
Violations are written to the review file and the exit status is 2; nothing is silently relaxed.

  make_lock.py lock   --report R.json --out requirements.lock --review lock_review.json [--lock-date YYYY-MM-DD]
  make_lock.py verify --lock requirements.lock --freeze freeze.txt
"""
import argparse
import json
import re
import sys
import urllib.error
import urllib.request
from datetime import date, datetime, timedelta
from pathlib import Path

PYPI = 'https://pypi.org/pypi/%s/%s/json'


def norm(name):
    return re.sub(r'[-_.]+', '-', name).lower()


def item_hash(item):
    info = item['download_info']['archive_info']
    sha = (info.get('hashes') or {}).get('sha256')
    if not sha and info.get('hash', '').startswith('sha256='):
        sha = info['hash'].split('=', 1)[1]
    return sha


def pypi_upload_date(name, version, filename):
    try:
        with urllib.request.urlopen(PYPI % (name, version), timeout=30) as r:
            doc = json.load(r)
    except (urllib.error.URLError, OSError, ValueError) as exc:
        return None, 'lookup failed: %r' % (exc,)
    for f in doc.get('urls', []):
        if f['filename'] == filename:
            return datetime.fromisoformat(f['upload_time_iso_8601'].replace('Z', '+00:00')).date(), None
    return None, 'artifact %s not listed on PyPI' % filename


def cmd_lock(args):
    report = json.loads(Path(args.report).read_text())
    lock_date = date.fromisoformat(args.lock_date) if args.lock_date else date.today()
    cutoff = lock_date - timedelta(days=args.min_age_days)
    rows, violations, extra_indexes = [], [], set()
    for item in report['install']:
        meta = item['metadata']
        name, version = norm(meta['name']), meta['version']
        url = item['download_info']['url']
        filename = url.rsplit('/', 1)[-1].split('#')[0]
        sha = item_hash(item)
        row = dict(name=name, version=version, filename=filename, url=url, sha256=sha)
        if not sha:
            violations.append(dict(package=name, problem='no SHA-256 in the resolution report'))
        if not filename.endswith('.whl'):
            violations.append(dict(package=name, problem='not a binary wheel: %s' % filename))
        host = re.match(r'https?://([^/]+)/', url).group(1)
        row['host'] = host
        if host.endswith('pythonhosted.org'):
            uploaded, err = pypi_upload_date(name, version, filename)
            row['uploaded'] = uploaded.isoformat() if uploaded else None
            if err or uploaded is None:
                violations.append(dict(package=name, problem=err or 'upload date unknown'))
            elif uploaded > cutoff:
                violations.append(dict(package=name, problem='released %s, newer than %s (min age %d days)'
                                       % (uploaded, cutoff, args.min_age_days)))
        else:
            row['uploaded'] = None
            row['note'] = 'non-PyPI artifact; age not checked'
            extra_indexes.add('https://%s/%s' % (host, '/'.join(url.split('/')[3:5])) if 'pytorch' in host else host)
        rows.append(row)
    rows.sort(key=lambda r: r['name'])
    lines = ['# requirements.lock generated by make_lock.py from a pip --dry-run --report resolution.',
             '# lock-date %s  min-age-days %d  python tags per the resolving interpreter.' % (lock_date, args.min_age_days),
             '# Install with: pip install --require-hashes --no-deps --only-binary=:all: -r requirements.lock',
             '--index-url https://pypi.org/simple']
    if any(r['host'] == 'download.pytorch.org' for r in rows):
        lines.append('--extra-index-url https://download.pytorch.org/whl/cpu')
    for r in rows:
        lines.append('%s==%s \\' % (r['name'], r['version']))
        lines.append('    --hash=sha256:%s' % r['sha256'])
    Path(args.out).write_text('\n'.join(lines) + '\n')
    review = dict(lock_date=lock_date.isoformat(), min_age_days=args.min_age_days, packages=rows,
                  violations=violations, status='BLOCKED' if violations else 'PASS')
    Path(args.review).write_text(json.dumps(review, indent=2) + '\n')
    print('packages: %d  violations: %d' % (len(rows), len(violations)))
    for v in violations:
        print('  VIOLATION', v)
    return 2 if violations else 0


def parse_lock(path):
    pins = {}
    for line in Path(path).read_text().splitlines():
        m = re.match(r'^([A-Za-z0-9_.-]+)==(\S+?)(?:\s*\\)?$', line.strip())
        if m:
            pins[norm(m.group(1))] = m.group(2)
    return pins


def cmd_verify(args):
    pins = parse_lock(args.lock)
    frozen = {}
    for line in Path(args.freeze).read_text().splitlines():
        m = re.match(r'^([A-Za-z0-9_.-]+)==(\S+)$', line.strip())
        if m:
            frozen[norm(m.group(1))] = m.group(2)
    ignorable = {'pip', 'setuptools', 'wheel'}
    missing = sorted(set(pins) - set(frozen))
    extra = sorted(set(frozen) - set(pins) - ignorable)
    mismatch = sorted(k for k in set(pins) & set(frozen) if pins[k] != frozen[k])
    print(json.dumps(dict(missing=missing, extra=extra, mismatch=mismatch, locked=len(pins), frozen=len(frozen))))
    return 0 if not (missing or extra or mismatch) else 2


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest='cmd', required=True)
    a = sub.add_parser('lock')
    a.add_argument('--report', required=True)
    a.add_argument('--out', required=True)
    a.add_argument('--review', required=True)
    a.add_argument('--lock-date')
    a.add_argument('--min-age-days', type=int, default=14)
    b = sub.add_parser('verify')
    b.add_argument('--lock', required=True)
    b.add_argument('--freeze', required=True)
    args = p.parse_args()
    return {'lock': cmd_lock, 'verify': cmd_verify}[args.cmd](args)


if __name__ == '__main__':
    sys.exit(main())
